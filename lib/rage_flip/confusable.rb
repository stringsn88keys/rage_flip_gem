module RageFlip
  class Confusable
    # Homoglyphs (Cyrillic, Greek, Armenian, Cherokee, etc.), unaccented letter
    # variants, and allographs (fullwidth, bold, script, fraktur, monospace).
    CONFUSABLES = {
      "a" => %w[а ɑ α ⍺ ａ 𝐚 𝒶 𝔞 𝚊],
      "b" => %w[Ь ᖯ ｂ 𝐛 𝒷 𝔟 𝚋],
      "c" => %w[с ϲ ᴄ ⅽ ｃ 𝐜 𝒸 𝔠 𝚌],
      "d" => %w[ԁ ⅾ ｄ 𝐝 𝒹 𝔡 𝚍],
      "e" => %w[е ҽ ℮ ｅ 𝐞 ℯ 𝔢 𝚎],
      "f" => %w[ꬵ ｆ 𝐟 𝒻 𝔣 𝚏],
      "g" => %w[ɡ ց ｇ 𝐠 ℊ 𝔤 𝚐],
      "h" => %w[һ հ ｈ 𝐡 𝒽 𝔥 𝚑],
      "i" => %w[і ı ɩ ι ⅰ ｉ 𝐢 𝒾 𝔦 𝚒],
      "j" => %w[ј ϳ ｊ 𝐣 𝒿 𝔧 𝚓],
      "k" => %w[ĸ κ ｋ 𝐤 𝓀 𝔨 𝚔],
      "l" => %w[ӏ ǀ ⅼ ℓ ｌ 𝐥 𝓁 𝔩 𝚕],
      "m" => %w[ⅿ ｍ 𝐦 𝓂 𝔪 𝚖],
      "n" => %w[ո ռ ｎ 𝐧 𝓃 𝔫 𝚗],
      "o" => %w[о ο օ ᴏ ｏ 𝐨 ℴ 𝔬 𝚘],
      "p" => %w[р ρ ｐ 𝐩 𝓅 𝔭 𝚙],
      "q" => %w[ԛ զ ｑ 𝐪 𝓆 𝔮 𝚚],
      "r" => %w[г ꭇ ｒ 𝐫 𝓇 𝔯 𝚛],
      "s" => %w[ѕ ꜱ ｓ 𝐬 𝓈 𝔰 𝚜],
      "t" => %w[ｔ 𝐭 𝓉 𝔱 𝚝],
      "u" => %w[υ ս ᴜ ｕ 𝐮 𝓊 𝔲 𝚞],
      "v" => %w[ν ѵ ᴠ ⅴ ｖ 𝐯 𝓋 𝔳 𝚟],
      "w" => %w[ԝ ᴡ ｗ 𝐰 𝓌 𝔴 𝚠],
      "x" => %w[х ⅹ ｘ 𝐱 𝓍 𝔵 𝚡],
      "y" => %w[у ү ɣ ｙ 𝐲 𝓎 𝔶 𝚢],
      "z" => %w[ᴢ ｚ 𝐳 𝓏 𝔷 𝚣],
      "A" => %w[А Α Ꭺ ᗅ Ａ 𝐀 𝒜 𝔄 𝙰],
      "B" => %w[В Β Ᏼ ℬ Ｂ 𝐁 𝔅 𝙱],
      "C" => %w[С Ϲ Ꮯ Ⅽ ℭ Ｃ 𝐂 𝒞 𝙲],
      "D" => %w[Ꭰ Ⅾ Ｄ 𝐃 𝒟 𝔇 𝙳],
      "E" => %w[Е Ε Ꭼ Ｅ 𝐄 ℰ 𝔈 𝙴],
      "F" => %w[Ϝ ᖴ Ｆ 𝐅 ℱ 𝔉 𝙵],
      "G" => %w[Ԍ Ꮐ Ｇ 𝐆 𝒢 𝔊 𝙶],
      "H" => %w[Н Η Ꮋ ℋ ℌ Ｈ 𝐇 𝙷],
      "I" => %w[І Ι Ӏ Ⅰ Ｉ 𝐈 ℐ ℑ 𝙸],
      "J" => %w[Ј Ꭻ Ｊ 𝐉 𝒥 𝔍 𝙹],
      "K" => %w[К Κ Ꮶ K Ｋ 𝐊 𝒦 𝔎 𝙺],
      "L" => %w[Ꮮ ᒪ Ⅼ Ｌ 𝐋 ℒ 𝔏 𝙻],
      "M" => %w[М Μ Ꮇ Ⅿ Ｍ 𝐌 ℳ 𝔐 𝙼],
      "N" => %w[Ν Ｎ 𝐍 𝒩 𝔑 𝙽],
      "O" => %w[О Ο Օ Ｏ 𝐎 𝒪 𝔒 𝙾],
      "P" => %w[Р Ρ Ꮲ Ｐ 𝐏 𝒫 𝔓 𝙿],
      "Q" => %w[Ԛ Ｑ 𝐐 𝒬 𝔔 𝚀],
      "R" => %w[Ꭱ Ꮢ ℛ ℜ Ｒ 𝐑 𝚁],
      "S" => %w[Ѕ Ꮪ Ｓ 𝐒 𝒮 𝔖 𝚂],
      "T" => %w[Т Τ Ꭲ Ｔ 𝐓 𝒯 𝔗 𝚃],
      "U" => %w[Ս ᑌ Ｕ 𝐔 𝒰 𝔘 𝚄],
      "V" => %w[Ѵ Ꮩ Ⅴ Ｖ 𝐕 𝒱 𝔙 𝚅],
      "W" => %w[Ԝ Ꮃ Ｗ 𝐖 𝒲 𝔚 𝚆],
      "X" => %w[Х Χ Ⅹ Ｘ 𝐗 𝒳 𝔛 𝚇],
      "Y" => %w[Υ Ү Ｙ 𝐘 𝒴 𝔜 𝚈],
      "Z" => %w[Ζ Ꮓ ℤ Ｚ 𝐙 𝒵 ℨ 𝚉]
    }.freeze

    def self.process(text)
      text.each_char.map { |c| CONFUSABLES[c]&.sample || c }.join
    end
  end
end
